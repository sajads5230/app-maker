import { Jimp } from 'jimp';
import path from 'path';
import fs from 'fs';

export interface IconGenerationResult {
  success: boolean;
  generatedFiles: string[];
  error?: string;
}

export class AppIconGenerator {
  /**
   * Generates all required Android and Web icons from a source image
   */
  static async generate(sourceImagePath: string, flutterProjectDir: string): Promise<IconGenerationResult> {
    const generatedFiles: string[] = [];

    try {
      if (!fs.existsSync(sourceImagePath)) {
        throw new Error(`Source image not found: ${sourceImagePath}`);
      }

      const image = await Jimp.read(sourceImagePath);

      // 1. Android Mipmap densities
      const androidResDir = path.join(flutterProjectDir, 'android', 'app', 'src', 'main', 'res');
      const mipmapSizes: Record<string, number> = {
        'mipmap-mdpi': 48,
        'mipmap-hdpi': 72,
        'mipmap-xhdpi': 96,
        'mipmap-xxhdpi': 144,
        'mipmap-xxxhdpi': 192,
      };

      for (const [folder, size] of Object.entries(mipmapSizes)) {
        const targetFolder = path.join(androidResDir, folder);
        if (!fs.existsSync(targetFolder)) {
          fs.mkdirSync(targetFolder, { recursive: true });
        }
        const targetPath = path.join(targetFolder, 'ic_launcher.png');
        const resized = image.clone();
        resized.resize({ w: size, h: size });
        await resized.write(targetPath as `${string}.${string}`);
        generatedFiles.push(targetPath);
      }

      // 2. Flutter Web Icons
      const webIconsDir = path.join(flutterProjectDir, 'web', 'icons');
      if (!fs.existsSync(webIconsDir)) {
        fs.mkdirSync(webIconsDir, { recursive: true });
      }

      // Icon-192
      const icon192 = image.clone();
      icon192.resize({ w: 192, h: 192 });
      const path192 = path.join(webIconsDir, 'Icon-192.png');
      await icon192.write(path192 as `${string}.${string}`);
      generatedFiles.push(path192);

      // Icon-512
      const icon512 = image.clone();
      icon512.resize({ w: 512, h: 512 });
      const path512 = path.join(webIconsDir, 'Icon-512.png');
      await icon512.write(path512 as `${string}.${string}`);
      generatedFiles.push(path512);

      // Favicon
      const favicon = image.clone();
      favicon.resize({ w: 32, h: 32 });
      const faviconPath = path.join(flutterProjectDir, 'web', 'favicon.png');
      await favicon.write(faviconPath as `${string}.${string}`);
      generatedFiles.push(faviconPath);

      console.log(`[AppIconGenerator] Successfully generated ${generatedFiles.length} icons for Flutter!`);
      return { success: true, generatedFiles };
    } catch (err: any) {
      console.error(`[AppIconGenerator] Error generating icons:`, err);
      return { success: false, generatedFiles, error: err.message };
    }
  }

  /**
   * Generates native Android & Flutter splash screen assets and XML config
   */
  static async generateSplash(
    splashImagePath: string,
    flutterProjectDir: string,
    backgroundColor: string = '#ffffff'
  ): Promise<boolean> {
    try {
      // 1. Assets folder for Flutter
      const assetsImgDir = path.join(flutterProjectDir, 'assets', 'images');
      if (!fs.existsSync(assetsImgDir)) {
        fs.mkdirSync(assetsImgDir, { recursive: true });
      }

      if (fs.existsSync(splashImagePath)) {
        const image = await Jimp.read(splashImagePath);
        const splashLogo = image.clone();
        splashLogo.resize({ w: 256, h: 256 });
        await splashLogo.write(path.join(assetsImgDir, 'splash_logo.png') as `${string}.${string}`);
      }

      // 2. Update Android launch_background.xml
      const launchBgPath = path.join(
        flutterProjectDir,
        'android',
        'app',
        'src',
        'main',
        'res',
        'drawable',
        'launch_background.xml'
      );

      const xmlContent = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by App Maker Engine -->
<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item>
        <shape android:shape="rectangle">
            <solid android:color="${backgroundColor}" />
        </shape>
    </item>
    <item>
        <bitmap
            android:gravity="center"
            android:src="@mipmap/ic_launcher" />
    </item>
</layer-list>
`;

      fs.writeFileSync(launchBgPath, xmlContent, 'utf-8');
      console.log(`[AppIconGenerator] Generated native launch_background.xml with color ${backgroundColor}`);
      return true;
    } catch (err) {
      console.error(`[AppIconGenerator] Splash error:`, err);
      return false;
    }
  }
}
